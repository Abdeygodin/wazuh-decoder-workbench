#!/usr/bin/env python3
"""Embed the stock Wazuh parent decoders into index.html.

The workbench warns when a stock decoder takes a line before the generated one
(stock files load before etc/decoders, and Wazuh uses the first parent decoder
that matches). Only parents decide that, so only parents are embedded.

    python3 tools/build-stock-decoders.py              # default tag below
    python3 tools/build-stock-decoders.py --tag v4.14.8
    python3 tools/build-stock-decoders.py --dir ../wazuh/ruleset/decoders --tag v4.14.8

No dependencies beyond the standard library.
"""
import argparse
import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

DEFAULT_TAG = "v4.14.8"
INDEX = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "index.html")
BEGIN = "/* STOCK-DECODERS:BEGIN — generated by tools/build-stock-decoders.py, do not edit */"
END = "/* STOCK-DECODERS:END */"


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode("utf-8", errors="replace")


def load_files(tag, local_dir):
    if local_dir:
        names = sorted(n for n in os.listdir(local_dir) if n.endswith(".xml"))
        return [(n, open(os.path.join(local_dir, n), encoding="utf-8", errors="replace").read()) for n in names]
    listing = json.loads(fetch(f"https://api.github.com/repos/wazuh/wazuh/contents/ruleset/decoders?ref={tag}"))
    names = sorted(e["name"] for e in listing if e["name"].endswith(".xml"))
    base = f"https://raw.githubusercontent.com/wazuh/wazuh/{tag}/ruleset/decoders/"
    return [(n, fetch(base + n)) for n in names]


def parse(text):
    """Read XML the way Wazuh's os_xml does: & is literal, \\< is an escaped <, entities stay as they are."""
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = text.replace("&", "&amp;").replace("\\<", "\\&lt;")
    return ET.fromstring("<root>" + text + "</root>")


def joined(dec, tag):
    """(pattern, type) of a decoder option, or (None, None). Repeated elements are concatenated, as
    decode-xml.c does (_loadmemory appends) — stock files split long prematches into several lines
    that end with |. An empty <program_name /> is an OS_Match that matches any program name."""
    els = dec.findall(tag)
    if not els:
        return None, None
    types = [e.get("type") for e in els if e.get("type")]
    return "".join(e.text or "" for e in els), types[-1] if types else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default=DEFAULT_TAG, help="Wazuh release tag (default %(default)s)")
    ap.add_argument("--dir", help="read ruleset/decoders from a local checkout instead of GitHub")
    args = ap.parse_args()

    files = load_files(args.tag, args.dir)
    parents = []
    for i, (name, text) in enumerate(files):
        for dec in parse(text).iter("decoder"):
            if dec.find("parent") is not None:
                continue
            parents.append([i, dec.get("name"), *joined(dec, "program_name"), *joined(dec, "prematch")])

    data = {"version": args.tag.lstrip("v"), "files": [n for n, _ in files], "parents": parents}
    block = f"{BEGIN}\nconst STOCK_DECODERS = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n{END}"

    html = open(INDEX, encoding="utf-8").read()
    if BEGIN not in html or END not in html:
        sys.exit("index.html has no STOCK-DECODERS markers")
    start, stop = html.index(BEGIN), html.index(END) + len(END)
    open(INDEX, "w", encoding="utf-8").write(html[:start] + block + html[stop:])
    print(f"embedded {len(parents)} parent decoders from {len(files)} files (Wazuh {data['version']}), {len(block) // 1024} KB")


if __name__ == "__main__":
    main()
